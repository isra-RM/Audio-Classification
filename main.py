import argparse
import logging

import pandas as pd
import pytorch_lightning as pl
import torch
from pytorch_lightning.callbacks import EarlyStopping, ModelCheckpoint
from pytorch_lightning.loggers import CSVLogger

from datamodule import AudioDataModule
from model import AudioClassifier
from utils import load_and_split_data, plot_training_curves


SEED = 123

logger = logging.getLogger(__name__)


def setup_logging(level=logging.INFO, log_file=None):
    handlers = [logging.StreamHandler()]
    if log_file:
        handlers.append(logging.FileHandler(log_file))
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(message)s",
        datefmt="%H:%M:%S",
        handlers=handlers,
    )

setup_logging()

class AudioClassificationExperiment:
    def __init__(self, 
                 csv_path, 
                 spec_dir="./spectrograms"
                 ):
        self.csv_path = csv_path
        self.spec_dir = spec_dir


    def run(self, batch_size=16, epochs=30, num_workers=0):
        
        pl.seed_everything(SEED, workers=True)
        torch.set_float32_matmul_precision("high")

        # Data
        train, val, test, num_classes = load_and_split_data(self.csv_path)

        # DataModule
        datamodule = AudioDataModule(
            train_df=train, val_df=val, test_df=test,spec_dir= self.spec_dir,batch_size=batch_size, num_workers=num_workers
        )

        # Model
        model = AudioClassifier(num_classes=num_classes)

        # Trainer setup
        # - CSVLogger writes per-epoch metrics to disk (used for plotting later).
        # - ModelCheckpoint saves the best model by validation loss.
        # - EarlyStopping halts training if validation loss stops improving,
        csv_logger = CSVLogger(save_dir="logs", name="audio_classifier")

        checkpoint_callback = ModelCheckpoint(
            monitor="val_loss", mode="min", save_top_k=1, filename="best-{epoch}-{val_loss:.2f}"
        )
        early_stopping = EarlyStopping(monitor="val_loss", mode="min", patience=5)

        trainer = pl.Trainer(
            max_epochs=epochs,
            accelerator="auto",
            devices="auto",
            logger=csv_logger,
            callbacks=[checkpoint_callback, early_stopping],
            log_every_n_steps=10,
        )

        # Training
        logger.info("Starting training (max %d epochs)", epochs)
        trainer.fit(model, datamodule=datamodule)
        logger.info("Best checkpoint: %s", checkpoint_callback.best_model_path)

        # Testing
        test_results = trainer.test(model, datamodule=datamodule, ckpt_path="best", weights_only=False)
        logger.info("Test Accuracy: %.2f%%", test_results[0]["test_acc"] * 100)

        # Plotting training progress
        metrics = pd.read_csv(f"{csv_logger.log_dir}/metrics.csv")
        plot_training_curves(metrics)



if __name__ == "__main__":
    
    parser = argparse.ArgumentParser(description="Audio Classification with PyTorch Lightning and timm ResNet18")

    parser.add_argument("--csv_path", type=str, default="files_paths.csv", help="Path to the CSV file containing audio file paths and labels")
    parser.add_argument("--spec_dir", type=str, default="./spectrograms", help="Folder with the spectrograms generated by the spectrogram script")
    
    args = parser.parse_args()

    experiment = AudioClassificationExperiment(
        csv_path=args.csv_path, 
        spec_dir=args.spec_dir
        )
    
    experiment.run()